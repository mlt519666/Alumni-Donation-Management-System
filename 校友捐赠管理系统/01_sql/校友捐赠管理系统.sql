CREATE TABLE 捐赠理事表
(捐赠理事编号 char(10) PRIMARY KEY,
姓名 varchar(30) not null,
性别 char(2) check(性别 = '男' or 性别 = '女'),
电话号码 char(11)
)

CREATE TABLE 捐赠分配表
(分配编号 char(10) PRIMARY KEY,
分配金额 money not null,
分配时间 datetime not null
)

CREATE TABLE 捐赠项目表
(项目编号 char(10) PRIMARY KEY,
项目名称 varchar(40) not null,
所需金额 money not null,
开始时间 date not null 
)

CREATE TABLE 捐赠受益人表
(受益人编号 char(10) PRIMARY KEY,
姓名 varchar(30) not null,
性别 char(2) check(性别 = '男' or 性别 = '女'),
身份 varchar(30) not null,
电话号码 char(11)
)

CREATE TABLE 捐赠表
(校友编号 char(10) PRIMARY KEY,
姓名 varchar(30) not null,
性别 char(2) check(性别 = '男' or 性别 = '女'),
工作职务 varchar(30),
单位 varchar(30),
电话号码 char(11),
入学年份 date not null,
院系 char(15),
班级 char(15),
捐赠理事编号 char(10) foreign key references 捐赠理事表(捐赠理事编号),
捐赠编号 char(10) not null,
捐赠时间 datetime not null,
捐赠金额 money not null,
捐赠类型 varchar(20) check(捐赠类型 in ('一次性捐赠','周期性捐赠')),
使用方式 varchar(20) check(使用方式 in ('仅资助项目','仅资助个人','无特殊要求'))
)

CREATE TABLE 负责表
(捐赠理事编号 char(10) foreign key references 捐赠理事表(捐赠理事编号),
分配编号 char(10) foreign key references 捐赠分配表(分配编号),
primary key(捐赠理事编号,分配编号)
)

CREATE TABLE 资助关系表
(受益人编号 char(10) foreign key references 捐赠受益人表(受益人编号),
分配编号 char(10) foreign key references 捐赠分配表(分配编号),
primary key(受益人编号,分配编号)
)

CREATE TABLE 分配关系表
(捐赠项目编号 char(10) foreign key references 捐赠项目表(项目编号),
分配编号 char(10) foreign key references 捐赠分配表(分配编号),
primary key(捐赠项目编号,分配编号)
)

CREATE TABLE 理事与项目管理表
(捐赠理事编号 char(10) foreign key references 捐赠理事表(捐赠理事编号),
捐赠项目编号 char(10) foreign key references 捐赠项目表(项目编号),
primary key(捐赠理事编号,捐赠项目编号),
是否分配 bit check(是否分配 in (0,1))
)

CREATE TABLE 理事与受益人管理表
(捐赠理事编号 char(10) foreign key references 捐赠理事表(捐赠理事编号),
受益人编号 char(10) foreign key references 捐赠受益人表(受益人编号),
primary key(捐赠理事编号,受益人编号),
是否分配 bit check(是否分配 in (0,1))
)

CREATE TABLE User_ 
(userID char(10) unique not null,
role char(10) check (role in('校友','捐赠理事','测试')),
userName char(30) unique not null, 
userPassword varchar(20) not null,
primary key(userID)
)

